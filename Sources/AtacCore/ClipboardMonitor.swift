import AppKit
import ApplicationServices
import Carbon.HIToolbox
import Foundation

public protocol PasteboardBackend: AnyObject {
    var changeCount: Int { get }
    var types: [NSPasteboard.PasteboardType]? { get }
    func string(forType dataType: NSPasteboard.PasteboardType) -> String?
    func data(forType dataType: NSPasteboard.PasteboardType) -> Data?
    func readFileURLPaths() -> [String]
    @discardableResult func clearContents() -> Int
    @discardableResult func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool
    @discardableResult func setData(_ data: Data?, forType dataType: NSPasteboard.PasteboardType) -> Bool
    func writeFileURLPaths(_ paths: [String])
}

public final class SystemPasteboardBackend: PasteboardBackend {
    private let pasteboard: NSPasteboard

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public var changeCount: Int { pasteboard.changeCount }
    public var types: [NSPasteboard.PasteboardType]? { pasteboard.types }

    public func string(forType dataType: NSPasteboard.PasteboardType) -> String? {
        pasteboard.string(forType: dataType)
    }

    public func data(forType dataType: NSPasteboard.PasteboardType) -> Data? {
        pasteboard.data(forType: dataType)
    }

    public func readFileURLPaths() -> [String] {
        guard let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL] else {
            return []
        }
        return urls.map(\.path)
    }

    @discardableResult
    public func clearContents() -> Int {
        pasteboard.clearContents()
    }

    @discardableResult
    public func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool {
        pasteboard.setString(string, forType: dataType)
    }

    @discardableResult
    public func setData(_ data: Data?, forType dataType: NSPasteboard.PasteboardType) -> Bool {
        pasteboard.setData(data, forType: dataType)
    }

    public func writeFileURLPaths(_ paths: [String]) {
        let urls = paths.map { URL(fileURLWithPath: $0) as NSURL }
        pasteboard.writeObjects(urls)
    }
}

public final class ClipboardMonitor {
    public static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("Pasteboard generator type")
    ]

    public static let selfMarkerType = NSPasteboard.PasteboardType("com.atac.selfCopy")

    private let backend: PasteboardBackend
    private let store: HistoryStore
    private let settings: AppSettings

    private var timer: DispatchSourceTimer?
    private var lastChangeCount: Int
    private var ignoredChangeCount: Int = -1
    private var isSystemSleeping: Bool = false

    public convenience init(
        pasteboard: NSPasteboard = .general,
        store: HistoryStore,
        settings: AppSettings = .shared
    ) {
        self.init(backend: SystemPasteboardBackend(pasteboard: pasteboard), store: store, settings: settings)
    }

    public init(
        backend: PasteboardBackend,
        store: HistoryStore,
        settings: AppSettings = .shared
    ) {
        self.backend = backend
        self.store = store
        self.settings = settings
        self.lastChangeCount = backend.changeCount

        observeWorkspacePowerEvents()
    }

    deinit {
        stop()
        NSWorkspace.shared.notificationCenter.removeObserver(self)
    }

    public func start() {
        stop()
        guard !settings.isPaused, !isSystemSleeping else { return }

        lastChangeCount = backend.changeCount
        let intervalMs = settings.pollIntervalMs
        // Generous timer leeway lets macOS coalesce CPU wakeups for near-0% idle energy impact
        let leewayMs = max(120, intervalMs / 3)

        let source = DispatchSource.makeTimerSource(queue: .main)
        source.schedule(
            deadline: .now() + .milliseconds(intervalMs),
            repeating: .milliseconds(intervalMs),
            leeway: .milliseconds(leewayMs)
        )
        source.setEventHandler { [weak self] in
            self?.pollOnce()
        }
        source.resume()
        self.timer = source
    }

    public func stop() {
        timer?.cancel()
        timer = nil
    }

    public func reconfigure() {
        store.enforceLimit(maxUnpinnedCount: settings.maxHistoryCount)
        if settings.isPaused || isSystemSleeping {
            stop()
        } else {
            start()
        }
    }

    public func pollOnce() {
        let currentCount = backend.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        guard currentCount != ignoredChangeCount else { return }
        guard !settings.isPaused else { return }

        // Wrap extraction in autoreleasepool so any transient NSData / NSBitmapImageRep frees immediately
        autoreleasepool {
            captureCurrentPasteboard()
        }
    }

    private func captureCurrentPasteboard() {
        let availableTypes = Set(backend.types ?? [])
        guard !availableTypes.isEmpty else { return }

        if availableTypes.contains(Self.selfMarkerType) {
            return
        }

        if settings.ignoreConcealed && !availableTypes.isDisjoint(with: Self.concealedTypes) {
            return
        }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName

        // 1. Check file URLs first (Finder file copies)
        if availableTypes.contains(.fileURL) {
            let paths = backend.readFileURLPaths()
            if !paths.isEmpty, let item = ClipboardItem.makeFiles(paths: paths, sourceAppName: sourceApp) {
                store.record(item, maxUnpinnedCount: settings.maxHistoryCount)
                return
            }
        }

        // 2. Check plain text / URLs
        if let str = backend.string(forType: .string),
           let item = ClipboardItem.makeText(str, sourceAppName: sourceApp) {
            store.record(item, maxUnpinnedCount: settings.maxHistoryCount)
            return
        }

        // 3. Check images (disk-backed so zero bitmap data stays in RAM)
        if settings.captureImages {
            captureImageIfPresent(availableTypes: availableTypes, sourceApp: sourceApp)
        }
    }

    private func captureImageIfPresent(availableTypes: Set<NSPasteboard.PasteboardType>, sourceApp: String?) {
        let maxImageBytes = 15 * 1024 * 1024

        var pngData: Data?
        var width = 0
        var height = 0

        if availableTypes.contains(.png), let rawPNG = backend.data(forType: .png), rawPNG.count <= maxImageBytes {
            pngData = rawPNG
            if let rep = NSBitmapImageRep(data: rawPNG) {
                width = rep.pixelsWide
                height = rep.pixelsHigh
            }
        } else if availableTypes.contains(.tiff), let rawTIFF = backend.data(forType: .tiff), rawTIFF.count <= maxImageBytes * 2 {
            if let rep = NSBitmapImageRep(data: rawTIFF),
               let converted = rep.representation(using: .png, properties: [.compressionFactor: 0.85]),
               converted.count <= maxImageBytes {
                pngData = converted
                width = rep.pixelsWide
                height = rep.pixelsHigh
            }
        }

        guard let finalData = pngData, !finalData.isEmpty else { return }
        let hash = ClipboardItem.fnv1a64(finalData)

        if let existing = store.items.first(where: { $0.kind == .image && $0.contentHash == hash && $0.byteSize == finalData.count }),
           let existingBlob = existing.blobFileName {
            let dup = ClipboardItem.makeImage(
                blobFileName: existingBlob,
                byteSize: finalData.count,
                width: width,
                height: height,
                dataHash: hash,
                sourceAppName: sourceApp
            )
            store.record(dup, maxUnpinnedCount: settings.maxHistoryCount)
            return
        }

        guard let blobFileName = store.writeBlobData(finalData, ext: "png") else { return }
        let item = ClipboardItem.makeImage(
            blobFileName: blobFileName,
            byteSize: finalData.count,
            width: width,
            height: height,
            dataHash: hash,
            sourceAppName: sourceApp
        )
        store.record(item, maxUnpinnedCount: settings.maxHistoryCount)
    }

    public func copyItemToPasteboard(_ item: ClipboardItem, plainTextOnly: Bool = false) {
        backend.clearContents()
        backend.setData(Data(), forType: Self.selfMarkerType)

        switch item.kind {
        case .text, .url:
            if let text = item.textContent {
                backend.setString(text, forType: .string)
            }
        case .file:
            if let paths = item.filePaths {
                if plainTextOnly {
                    backend.setString(paths.joined(separator: "\n"), forType: .string)
                } else {
                    backend.writeFileURLPaths(paths)
                }
            }
        case .image:
            if plainTextOnly {
                backend.setString(item.preview, forType: .string)
            } else if let blob = item.blobFileName, let data = store.readBlobData(named: blob) {
                backend.setData(data, forType: .png)
            }
        }

        ignoredChangeCount = backend.changeCount
        lastChangeCount = backend.changeCount
        store.bumpToTop(id: item.id)
    }

    public static func isAccessibilityTrusted(prompt: Bool = false) -> Bool {
        if prompt {
            let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
            return AXIsProcessTrustedWithOptions(options)
        }
        return AXIsProcessTrusted()
    }

    public static func synthesizeCommandV() {
        guard AXIsProcessTrusted(),
              let source = CGEventSource(stateID: .combinedSessionState),
              let keyDown = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false) else {
            return
        }
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand
        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
    }

    private func observeWorkspacePowerEvents() {
        let nc = NSWorkspace.shared.notificationCenter
        nc.addObserver(self, selector: #selector(handleSleepNotice), name: NSWorkspace.screensDidSleepNotification, object: nil)
        nc.addObserver(self, selector: #selector(handleSleepNotice), name: NSWorkspace.sessionDidResignActiveNotification, object: nil)
        nc.addObserver(self, selector: #selector(handleWakeNotice), name: NSWorkspace.screensDidWakeNotification, object: nil)
        nc.addObserver(self, selector: #selector(handleWakeNotice), name: NSWorkspace.sessionDidBecomeActiveNotification, object: nil)
    }

    @objc private func handleSleepNotice() {
        isSystemSleeping = true
        stop()
    }

    @objc private func handleWakeNotice() {
        isSystemSleeping = false
        if !settings.isPaused {
            pollOnce()
            start()
        }
    }
}
